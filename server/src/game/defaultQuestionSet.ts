const MEDIUM_RIENG = ['kd-r-1-3', 'kd-r-1-4', 'kd-r-2-3', 'kd-r-2-5', 'kd-r-3-3', 'kd-r-4-4', 'kd-r-4-5', 'kd-r-5-2', 'kd-r-5-5', 'kd-r-5-6'];
